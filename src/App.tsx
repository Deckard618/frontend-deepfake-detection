import { useEffect, useState } from "react";
import { Detector } from "./components/Detector";
import { HowItWorks } from "./components/HowItWorks";
import { ImageForensics } from "./components/ImageForensics";
import { VideoForensics } from "./components/VideoForensics";
import { Choice } from "./components/ui";
import { KOFI_URL, REPO_URL } from "./lib/links";

const HEADER_LINK = "rounded-lg border border-border px-3 py-1.5 text-sm transition hover:border-accent/60";

// Labels say what a visitor wants to do. The values are the URL hashes (#text, …) that links point to: keep them.
const TABS = [
  { value: "detect", label: "Check an image", hint: "Estimates whether an image was generated by AI" },
  { value: "text", label: "Check a text", hint: "Estimates whether a text was written by AI" },
  { value: "image", label: "Inspect an image", hint: "Forensic views to look for edits yourself: noise, edges, metadata…" },
  { value: "video", label: "Inspect a video", hint: "Frame-by-frame forensic views: motion, edges, optical flow" },
] as const;
type Tab = (typeof TABS)[number]["value"];

// Scrolls to the animation without changing the URL, whose hash names the tab.
function showHowItWorks() {
  const section = document.getElementById("how-it-works");
  const still = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  section?.scrollIntoView({ behavior: still ? "auto" : "smooth" });
  section?.focus({ preventScroll: true });
}

export default function App() {
  const [tab, setTab] = useState<Tab>(() => TABS.find((t) => `#${t.value}` === window.location.hash)?.value ?? "detect");
  const [image, setImage] = useState<File | null>(null); // shared by "Check an image" and "Inspect an image"
  const [text, setText] = useState("");
  const [video, setVideo] = useState<File | null>(null);

  useEffect(() => {
    window.history.replaceState(null, "", tab === "detect" ? window.location.pathname : `#${tab}`);
  }, [tab]);

  // Paste anywhere: images go to "Check an image" / "Inspect an image", videos to "Inspect a video", and on the
  // "Check a text" tab, text goes to the text box (a paste inside a text field is left to the field).
  useEffect(() => {
    const onPaste = (e: ClipboardEvent) => {
      const file = e.clipboardData?.files[0];
      if (file?.type.startsWith("video/")) {
        setVideo(file);
        setTab("video");
      } else if (file?.type.startsWith("image/")) {
        setImage(file);
        if (tab === "video") setTab("image");
        else if (tab === "text") setTab("detect");
      } else if (tab === "text" && !(e.target instanceof HTMLTextAreaElement || e.target instanceof HTMLInputElement)) {
        const pasted = e.clipboardData?.getData("text/plain");
        if (pasted) setText(pasted);
      }
    };
    window.addEventListener("paste", onPaste);
    return () => window.removeEventListener("paste", onPaste);
  }, [tab]);

  return (
    <div className="mx-auto flex min-h-screen max-w-5xl flex-col gap-6 px-4 py-10">
      <header className="flex flex-col gap-4">
        <div className="flex items-start justify-between gap-4">
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">AI Detection &amp; Forensics Lab</h1>
            <p className="mt-1 text-sm text-muted">Detect AI-generated content and inspect images and videos.</p>
          </div>
          <div className="flex shrink-0 flex-col items-end gap-2 sm:flex-row">
            {REPO_URL && (
              <a href={REPO_URL} target="_blank" rel="noopener noreferrer" className={HEADER_LINK}>
                Source code<span className="hidden sm:inline">&nbsp;on GitHub</span>
              </a>
            )}
            {KOFI_URL && (
              <a href={KOFI_URL} target="_blank" rel="noopener noreferrer" className={`flex items-center gap-1.5 ${HEADER_LINK}`}>
                <svg
                  aria-hidden
                  viewBox="0 0 24 24"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  className="h-4 w-4 text-accent"
                >
                  <path d="M4 9h12v5a6 6 0 0 1-12 0Z" />
                  <path d="M16 11h1.5a2.5 2.5 0 0 1 0 5H16" />
                  <path d="M8 3v3M12 3v3" />
                </svg>
                <span>
                  Support<span className="hidden sm:inline">&nbsp;on Ko-fi</span>
                </span>
              </a>
            )}
          </div>
        </div>
        <aside className="flex gap-2.5 rounded-lg border border-accent/30 bg-accent/5 px-3 py-2.5 text-sm">
          <svg
            aria-hidden
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth="2"
            strokeLinecap="round"
            strokeLinejoin="round"
            className="mt-0.5 h-4 w-4 shrink-0 text-accent"
          >
            <rect x="5" y="11" width="14" height="10" rx="2" />
            <path d="M8 11V7a4 4 0 0 1 8 0v4" />
          </svg>
          <p>
            <strong className="font-semibold">Everything runs on your device.</strong> Your images, videos and texts are
            never uploaded: the models run in your browser.{" "}
            <button type="button" onClick={showHowItWorks} className="font-medium text-accent hover:underline">
              How it works
            </button>
          </p>
        </aside>
        <Choice options={TABS} value={tab} onChange={setTab} />
      </header>

      <main>
        {tab === "detect" && <Detector task="image" image={image} onImage={setImage} />}
        {tab === "text" && <Detector task="text" text={text} onText={setText} />}
        {tab === "image" && <ImageForensics image={image} onImage={setImage} />}
        {tab === "video" && <VideoForensics file={video} onFile={setVideo} />}
      </main>

      <HowItWorks />

      <footer className="mt-auto flex flex-col gap-2 text-xs text-muted">
        <p>
          This site is a demo. Scores are probabilities and forensic views are indicators, not proof. Every detector makes
          mistakes, especially on content unlike its training data.
        </p>
        {KOFI_URL && (
          <p>
            It is free for everyone, with no ads and no tracking. Donations are optional and unlock nothing: if the site
            helps you, you can{" "}
            <a href={KOFI_URL} target="_blank" rel="noopener noreferrer" className="underline hover:text-fg">
              support it on Ko-fi
            </a>
            .
          </p>
        )}
        <nav className="[&_a:hover]:text-fg [&_a]:underline">
          <a href="/legal">Mentions légales</a> · <a href="/legal-en">Legal notice</a>
        </nav>
      </footer>
    </div>
  );
}
